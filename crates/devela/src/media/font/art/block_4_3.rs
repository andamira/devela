#[test]
fn test_font() {
    use crate::{CharIter, whilst};
    use ART_BLOCK_4_3 as FONT;

    whilst! { i in 0..FONT.len(); {
        #[cfg(feature = "std")]
        crate::cdbg![1# FONT[i]]; // show the symbol we're testing
        whilst! { j in 0..3; {
            let row = FONT[i][j];
            let iter = CharIter::<&str>::new(row);
            assert_eq![iter.count(), 4];
        }}
    }}
}
