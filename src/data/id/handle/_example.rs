handle! {
    [
        index: u8 + crate::NonMaxU8;
        kind: u8;
        revision: u16;
    ]

    #[doc = crate::_tags!(example uid)]
    /// An example general handle.
    #[doc = crate::_doc_meta!{
        location("data/id/handle", struct HandleExample),
        test_size_of(HandleExample = 4|32; niche Option),
    }]
    /// Generated by [`handle!`].
    ///
    /// Demonstrates three independently represented components:
    /// - a niche-aware `index`,
    /// - a `kind` discriminator,
    /// - and a `revision` value.
    ///
    /// Their interpretation and external validity are left to the resolver.
    ///
    /// ```
    /// use devela::{handle, NonMaxU8};
    ///
    /// handle! {
    ///     [
    ///         index: u8 + NonMaxU8;
    ///         kind: u8;
    ///         revision: u16;
    ///     ]
    ///     /// An example general handle.
    ///     pub HandleExample;
    /// }
    /// ```
    #[doc = crate::_DOC_HANDLE_METHODS!()]
    pub HandleExample;
}

